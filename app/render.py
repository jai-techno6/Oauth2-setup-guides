"""Markdown export, so a guide can be pasted into Slack, Notion, a PR, or an email."""

from __future__ import annotations

from .models import Evidenced, Guide

BADGE = {"tested": "TESTED", "cited": "CITED", "inferred": "INFERRED", "unknown": "UNKNOWN"}
WHO = {"agent": "Agent", "human": "You", "either": "Agent or you"}


def _ev(guide: Guide, item: Evidenced) -> str:
    refs = "".join(f"[{i}]" for i in item.source_ids)
    tag = BADGE[item.evidence]
    if item.evidence == "cited" and item.quote_check == "verified":
        tag += ", quote checked"
    return f" _({tag}{' ' + refs if refs else ''})_"


def guide_to_markdown(guide: Guide, base_url: str = "") -> str:
    g = guide
    out: list[str] = []
    out.append(f"# OAuth app setup guide: {g.app_name}")
    origin = "Curated and spot-checked" if g.origin == "curated" else f"Generated by research agent ({g.model})"
    out.append(f"{origin} on {g.generated_at}. Confidence: **{g.confidence()}**.")
    if base_url:
        out.append(f"Live version: {base_url}/guides/{g.slug}")
    out.append("")
    out.append(f"**Difficulty: {g.tier_label()}** - {g.tier_blurb()}{_ev(g, g.difficulty_claim)}")
    if g.difficulty_claim.text:
        out.append(f"> {g.difficulty_claim.text}")
    out.append("")
    out.append(g.summary)
    out.append("")
    out.append("## Time and effort")
    out.append(f"- **Hands-on:** {g.time.hands_on.text}{_ev(g, g.time.hands_on)}")
    out.append(f"- **Approval wait:** {g.time.approval_wait.text}{_ev(g, g.time.approval_wait)}")
    out.append(f"- **Fastest path:** {g.time.fastest_path.text}{_ev(g, g.time.fastest_path)}")
    out.append("")
    out.append("## Do you need your own OAuth app? (Composio)")
    status = {"managed": "Composio-managed OAuth available", "byo_required": "Bring your own OAuth app",
              "unknown": "Not confirmed"}[g.composio.status]
    out.append(f"**{status}.** {g.composio.claim.text}{_ev(g, g.composio.claim)}")
    out.append("")
    out.append("## What the agent can do vs. where you take over")
    out.append("**Agent can:**")
    out.extend(f"- {x}" for x in g.agent_can)
    out.append("")
    out.append("**You must:**")
    out.extend(f"- {x}" for x in g.human_must)
    if g.walls():
        out.append("")
        out.append("**Where the agent was stopped (tested):**")
        out.extend(f"- {p.check}: {p.result} ({p.url})" for p in g.walls())
    out.append("")
    out.append("## Steps")
    n = 0
    for phase in g.phases:
        out.append(f"### {phase.name}")
        if phase.summary:
            out.append(phase.summary)
        for s in phase.steps:
            n += 1
            who = WHO[s.who]
            extra = f" Why you: {s.why_human}." if s.who != "agent" and s.why_human else ""
            link = f" ({s.url})" if s.url else ""
            out.append(f"{n}. [ ] **{s.title}** [{who}] {s.detail}{extra}{link}{_ev(g, s)}")
        out.append("")
    for title, items in (("Requirements", g.requirements), ("Gotchas", g.gotchas)):
        if items:
            out.append(f"## {title}")
            out.extend(f"- **{i.title}:** {i.detail}{_ev(g, i)}" for i in items)
            out.append("")
    if g.blockers:
        out.append("## Blockers and workarounds")
        for b in g.blockers:
            wa = f" Workaround: {b.workaround}" if b.workaround else ""
            out.append(f"- **{b.title}:** {b.detail}{wa}{_ev(g, b)}")
        out.append("")
    if g.conflicts:
        out.append("## Where sources disagree")
        for c in g.conflicts:
            refs = "".join(f"[{i}]" for i in c.source_ids)
            out.append(f"- **{c.topic}:** {c.positions} {c.resolution} {refs}".rstrip())
        out.append("")
    if g.unknowns:
        out.append("## Still unknown")
        out.extend(f"- {u}" for u in g.unknowns)
        out.append("")
    if g.probes:
        out.append("## What was tested")
        out.extend(f"- {p.check} - **{p.outcome}**: {p.result} ({p.checked_at})" for p in g.probes)
        out.append("")
    out.append("## Sources")
    kinds = {"official": "official", "third_party": "third-party", "composio": "Composio", "probe": "live check"}
    out.extend(f"[{s.id}] {s.title or s.url} ({kinds[s.kind]}, accessed {s.accessed}) {s.url}" for s in g.sources)
    out.append("")
    out.append("_Evidence labels: TESTED = observed by a check we ran; CITED = stated by a linked source; "
               "INFERRED = reasoning, not stated by a source; UNKNOWN = could not determine._")
    return "\n".join(out) + "\n"
